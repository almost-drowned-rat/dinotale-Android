int main(int argc, char** argv) {
    std::set_terminate(report_unhandled_exception_and_abort);
#ifdef __ANDROID__
    // Native crashes into logcat (tag DinoTale-Crash), the app's folders from MainActivity, and a working directory
    // with the UI assets AppSetup.java copied out of the APK (the process starts in "/"). RT64 finds its data folder
    // through HOME, which an Android app process does not have.
    androidport::crash::install();
    androidport::init_from_args(argc, argv);
    if (!androidport::internal_files_dir().empty()) {
        SDL_setenv("HOME", androidport::internal_files_dir().c_str(), 1);
        std::error_code cwd_error;
        std::filesystem::current_path(androidport::internal_files_dir(), cwd_error);
    }
#endif

    // Command-line options (command_line.cpp), read before the game moves to its own folder.
    dinotale_attach_console(argc);
    DinoTaleCommandLine command_line;
    if (!dinotale_parse_command_line(argc, argv, command_line)) {
        fflush(stdout);
        return EXIT_SUCCESS;
    }

    find_assets_folder();

    recomp::Version project_version{};
    if (!recomp::Version::from_string(version_string, project_version)) {
        fprintf(stderr, "Invalid version string: %s\n", version_string.c_str());
        return EXIT_FAILURE;
    }

    register_dinotale_overlays();

    NFD_Init();

    recompui::programconfig::set_program_name(program_name);
    recompui::programconfig::set_program_id(program_id);
    // A new install keeps its settings, saves and mods in the game's own folder.
    dinotale_use_portable_mode_by_default();

    SDL_InitSubSystem(SDL_INIT_AUDIO);
    if (!open_audio_device(game_frequency)) {
        fprintf(stderr, "Continuing without sound.\n");
    }

    // Exo 2 (SIL OFL 1.1, assets/EXO2_LICENSE.txt), a variable font covering
    // every weight the UI uses. The family name must match the one stored
    // inside the font file: recompui's generated base stylesheet sets
    // `font-family` to it, and RmlUi draws no text for a family it never
    // loaded.
    recompui::register_primary_font("Exo2.ttf", "Exo 2");
    // Fredoka SemiBold (SIL OFL 1.1, assets/FREDOKA_LICENSE.txt; a static
    // instance of Fredoka's variable font) for the launcher's logo and options.
    recompui::register_extra_font("FredokaSemiBold.ttf");

    recomp::register_config_path(recompui::file::get_app_folder_path());

    for (const auto& game : supported_games) {
        recomp::register_game(game);
    }
    // The game can also be picked inside a .zip or .7z (rom_archive.cpp).
    recomp::register_rom_archive_reader(dinotale_read_rom_archive);

    recompinput::players::set_single_player_mode(true);

    // recompui::config::init_modal() (called from UIState::create_menus(),
    // itself called from inside RT64::Application::setup() on the gfx
    // thread) hard-requires recompui::config::finalize() to have already
    // run -- without it, "loaded_configs" stays false and/or the config
    // system is left in a state RT64/recompui doesn't expect, which
    // crashes startup. So the config tabs are
    // created and finalized here, before recomp::start().
    recompui::config::GeneralTabOptions general_tab_options{};
    recompui::config::create_general_tab(general_tab_options);
    recomp::config::Config &graphics_tab = recompui::config::create_graphics_tab();
    dinotale_add_display_options(graphics_tab);
#ifndef __ANDROID__
    // Lossless Scaling frame generation needs the player's Windows Lossless.dll: not offered on Android.
    dinotale_add_frame_generation_options(graphics_tab);
#endif
#ifdef __ANDROID__
    // Settings > Android Options (after Graphics): the shader resolution, the shader pages of the menu Back opens
    // and the GPU driver.
    {
        recomp::config::Config &android_tab = recompui::config::create_config_tab("Android Options", "android_options", false);
        android_tab.add_enum_option(
            "shader_resolution",
            "Shader Resolution",
            "The size of the game's picture a RetroArch shader works on. "
            "<recomp-color primary>Original</recomp-color>: the N64's 240 lines, as in RetroArch - the look the shaders "
            "were made for (scanlines, CRT masks, pixel upscalers) and by far the lightest. "
            "<recomp-color primary>2x</recomp-color>: twice that. "
            "<recomp-color primary>Full</recomp-color>: the window's size - heavy shaders get slow.<br /><br />"
            "<b>Shader...</b> imports shader packs (.zip) and picks a preset, <b>Shader parameters...</b> changes "
            "the preset's settings, <b>GPU Driver (Turnip)...</b> installs a Vulkan driver (the app restarts).",
            std::vector<recomp::config::ConfigOptionEnumOption>{ { 0, "Original" }, { 1, "2x", "2x" }, { 2, "Full" } },
            0u,
            true);   // shown as a button (below)
    }
    // Settings > Android Options: Shader, Shader Resolution, Shader parameters, an empty line, GPU Driver - each a
    // button with what's in use beside it (lib-patches/RecompFrontend/0007). Shader Resolution's
    // option itself is hidden; its button goes through Original, 2x and Full.
    {
        using recompui::config::OptionButton;
        auto add = [](const char *label, std::function<void()> callback, std::function<std::string()> value, bool before,
                      bool gap_before, std::function<void()> reset) {
            OptionButton button;
            button.label = label;
            button.callback = std::move(callback);
            button.value = std::move(value);
            button.before = before;
            button.gap_before = gap_before;
            button.reset = std::move(reset);
            recompui::config::add_option_button("shader_resolution", std::move(button));
        };
        static const char *const resolution_names[] = { "Original", "2x", "Full" };
        auto resolution = []() -> uint32_t {
            const auto value = recompui::config::get_config("android_options").get_option_value("shader_resolution");
            const uint32_t *index = std::get_if<uint32_t>(&value);
            return index != nullptr && *index < 3 ? *index : 0;
        };
        add("Shader...", []() { android_open_shader_menu(0); }, []() { return android_shader_name(); }, true, false,
            []() { android_reset_shader(0); });
        add("Shader Resolution", [resolution]() {
                recomp::config::Config &config = recompui::config::get_config("android_options");
                config.set_option_value("shader_resolution", (resolution() + 1) % 3);
                config.save_config();
            }, [resolution]() { return std::string(resolution_names[resolution()]); }, false, false, []() {
                recomp::config::Config &config = recompui::config::get_config("android_options");
                config.set_option_value("shader_resolution", 0u);
                config.save_config();
            });
        add("Shader parameters...", []() { android_open_shader_menu(1); }, []() { return android_shader_params_summary(); },
            false, false, []() { android_reset_shader(1); });
        add("GPU Driver (Turnip)...", []() { show_android_gpu_driver_menu(); }, []() {
                // the driver's name comes from a file: asked once a second
                static std::string name;
                static std::chrono::steady_clock::time_point asked;
                const auto now = std::chrono::steady_clock::now();
                if (name.empty() || now - asked > std::chrono::seconds(1)) {
                    name = dk64driver::active_name();
                    asked = now;
                }
                return name;
            }, false, true, nullptr);
    }
#endif
    recompui::config::create_controls_tab();
    recompui::config::create_sound_tab();
    dinotale_add_cheat_tabs();
#ifdef __ANDROID__
    for (const std::string &id : { recompui::config::general::id, recompui::config::graphics::id, std::string("android_options"),
                                   recompui::config::controls::id, recompui::config::sound::id, std::string("cheats"),
                                   std::string("hacks") }) {
        recompui::config::set_tab_visible(id, false);
    }
    create_android_card_tabs();
#endif
    recompui::config::create_mods_tab();
#ifdef __ANDROID__
    recompui::config::set_tab_visible(recompui::config::mods::id, false);
    recompui::config::create_card_tab("Mods", "card_mods", []() {
        std::vector<recompui::config::MenuCardEntry> l;
        l.push_back(recompui::config::header_card("Mods"));
        for (auto &e : recompui::config::mods_cards()) l.push_back(e);
        return l;
    });
#endif
    recompui::config::finalize();

    // Settings and the ROM from the command line, now that the saved settings are loaded.
    if (!dinotale_apply_command_line(command_line)) {
        fflush(stdout);
        std::_Exit(EXIT_SUCCESS);
    }
    // The runtime reads --game (from --play) and --game-mode itself.
    std::vector<char *> runtime_argv = { argv[0] };
    for (std::string &arg : command_line.runtime_args) {
        runtime_argv.push_back(arg.data());
    }

    recomp::rsp::callbacks_t rsp_callbacks{
        .get_rsp_microcode = get_rsp_microcode,
    };

    ultramodern::renderer::callbacks_t renderer_callbacks{
        .create_render_context = [](uint8_t* rdram, ultramodern::renderer::WindowHandle window_handle, bool developer_mode) {
            auto presentation_mode = ultramodern::renderer::PresentationMode::PresentEarly;
            return recompui::renderer::create_render_context(rdram, window_handle, presentation_mode, developer_mode);
        },
    };

    ultramodern::gfx_callbacks_t gfx_callbacks{
        .create_gfx = create_gfx,
        .create_window = create_window,
        .update_gfx = update_gfx,
    };

    ultramodern::audio_callbacks_t audio_callbacks{
        .queue_samples = queue_samples,
        .get_frames_remaining = get_frames_remaining,
        .set_frequency = set_frequency,
    };

    ultramodern::input::callbacks_t input_callbacks{
        .poll_input = recompinput::poll_inputs,
        .get_input = recompinput::profiles::get_n64_input,
        .set_rumble = recompinput::set_rumble,
        .get_connected_device_info = get_connected_device_info,
    };
#ifdef __ANDROID__
    // Touch buttons (android/: TouchOverlay.java, native/compat/virtual_pad.cpp): merged into controller 1's N64 input;
    // the Java side learns whether the game runs and whether a menu takes input.
    input_callbacks.poll_input = []() {
        recompinput::poll_inputs();
        androidport::virtualpad::update_game_state(ultramodern::is_game_started(), recompinput::game_input_disabled());
    };
    input_callbacks.get_input = [](int controller_num, uint16_t* buttons, float* x, float* y) {
        bool ret = recompinput::profiles::get_n64_input(controller_num, buttons, x, y);
        androidport::virtualpad::merge_input(controller_num, buttons, x, y);
        return ret;
    };
#endif

    ultramodern::events::callbacks_t events_callbacks{
        .vi_callback = on_vi,
        .gfx_init_callback = nullptr,
    };

    ultramodern::error_handling::callbacks_t error_handling_callbacks{
        .message_box = recompui::message_box,
    };

    ultramodern::threads::callbacks_t threads_callbacks{
        .get_game_thread_name = get_game_thread_name,
    };

    // The launcher screen: recompui's launcher with DinoTale's own scene and
    // layout (launcher.cpp, assets/launcher).
    recompui::register_launcher_init_callback(on_launcher_init);
    recompui::register_launcher_update_callback(dinotale::launcher_update);

    dinotale::restart::install(argc, argv);

    recomp::start({
        .argc = int(runtime_argv.size()),
        .argv = runtime_argv.data(),
        .project_version = project_version,
        .window_handle = {}, // created by gfx_callbacks.create_window
        .rsp_callbacks = rsp_callbacks,
        .renderer_callbacks = renderer_callbacks,
        .audio_callbacks = audio_callbacks,
        .input_callbacks = input_callbacks,
        .gfx_callbacks = gfx_callbacks,
        .events_callbacks = events_callbacks,
        .error_handling_callbacks = error_handling_callbacks,
        .threads_callbacks = threads_callbacks,
        .message_queue_control = {}, // the runtime's defaults
    });

    NFD_Quit();

    // The game's threads are never joined by the runtime and may still be
    // blocked on (or spinning over) runtime state when recomp::start
    // returns, so running static destructors/atexit handlers underneath
    // them can crash on quit -- exit directly instead (same approach as
    // other N64Recomp projects' main()).
    dinotale::restart::relaunch_if_requested();
    fflush(stdout);
    fflush(stderr);
    std::_Exit(EXIT_SUCCESS);
}
