// std::terminate (any uncaught C++ exception, on any thread -- recomp::start
// spawns several) leads straight into ucrtbase's fail-fast abort path, which
// tears the process down without running atexit handlers or flushing stdio
// buffers. That's why redirected runs (`... > run_output.txt 2>&1`) have
// been showing up empty even when something threw and printed nothing --
// this handler force-flushes and prints the exception's own message first
// so it actually survives redirection.
[[noreturn]] static void report_unhandled_exception_and_abort() {
    if (std::exception_ptr eptr = std::current_exception()) {
        try {
            std::rethrow_exception(eptr);
        } catch (const std::exception& e) {
            fprintf(stderr, "UNHANDLED EXCEPTION: %s\n", e.what());
        } catch (...) {
            fprintf(stderr, "UNHANDLED EXCEPTION: (unrecognized exception type)\n");
        }
    } else {
        fprintf(stderr, "std::terminate() called with no active exception.\n");
    }
    fflush(stdout);
    fflush(stderr);
    std::abort();
}

// The folder for the player's own RetroArch shaders (Settings > Graphics > Shader > Custom = custom.slangp in it):
// on Android the app's external folder (Android/data/<app>/files/shaders, reachable over USB), elsewhere next to
// the game. Created on first use, so players find it.
std::filesystem::path dinotale_user_shader_dir() {
#ifdef __ANDROID__
    std::filesystem::path dir = std::filesystem::path(androidport::external_files_dir()) / "shaders";
#else
    std::filesystem::path dir = std::filesystem::current_path() / "shaders";
#endif
    std::error_code ec;
    std::filesystem::create_directories(dir, ec);
    return dir;
}

// The UI loads assets/ relative to the working directory. When started from
// somewhere else (a debugger, a shortcut), use the exe's own folder, which
// the build fills with a copy of assets/.
static void find_assets_folder() {
    std::error_code ec;
    if (std::filesystem::exists("assets", ec)) {
        return;
    }
    char* base = SDL_GetBasePath();
    if (base == nullptr) {
        return;
    }
    std::filesystem::path exe_dir = std::filesystem::path(reinterpret_cast<const char8_t*>(base));
    SDL_free(base);
    if (std::filesystem::exists(exe_dir / "assets", ec)) {
        std::filesystem::current_path(exe_dir, ec);
    }
}
